void paintLoadingPlaceholder(void* displayHandle, unsigned long window)
{
	auto* display = static_cast<Display*>(displayHandle);
	if (display == nullptr || window == 0)
	{
		return;
	}

	XWindowAttributes attributes{};
	if (!XGetWindowAttributes(display, static_cast<Window>(window), &attributes))
	{
		return;
	}
	const int width = attributes.width;
	const int height = attributes.height;
	if (width <= 0 || height <= 0)
	{
		return;
	}

	const int screen = DefaultScreen(display);
	const int depth = DefaultDepth(display, screen);
	Pixmap canvas = XCreatePixmap(display, static_cast<Window>(window),
		static_cast<unsigned>(width), static_cast<unsigned>(height),
		static_cast<unsigned>(depth));
	if (canvas == 0)
	{
		return;
	}

	GC gc = XCreateGC(display, canvas, 0, nullptr);
	const auto allocate = [display, screen](const char* spec,
		unsigned long fallback) {
		XColor color{};
		Colormap map = DefaultColormap(display, screen);
		if (XAllocNamedColor(display, map, spec, &color, &color))
		{
			return color.pixel;
		}
		return fallback;
	};
	const unsigned long background = allocate("#2F2F2F",
		BlackPixel(display, screen));
	const unsigned long foreground = allocate("#FFFFFF",
		WhitePixel(display, screen));

	XSetForeground(display, gc, background);
	XFillRectangle(display, canvas, gc, 0, 0,
		static_cast<unsigned>(width), static_cast<unsigned>(height));

	Pixmap logo = XCreatePixmapFromBitmapData(display, canvas,
		reinterpret_cast<char*>(kLoadingLogoBits), kLoadingLogoWidth, kLoadingLogoHeight,
		background, foreground, static_cast<unsigned>(depth));
	if (logo != 0)
	{
		const int x = (width - kLoadingLogoWidth) / 2;
		const int y = (height - kLoadingLogoHeight) / 2;
		XCopyArea(display, logo, canvas, gc, 0, 0,
			kLoadingLogoWidth, kLoadingLogoHeight, x, y);
		XFreePixmap(display, logo);
	}

	XFontStruct* font = XLoadQueryFont(display, "fixed");
	if (font != nullptr)
	{
		const char* text = "Loading plugin GUI...";
		const int textWidth = XTextWidth(font, text,
			static_cast<int>(std::strlen(text)));
		XSetFont(display, gc, font->fid);
		XSetForeground(display, gc, foreground);
		XDrawString(display, canvas, gc, (width - textWidth) / 2,
			height / 2 + 64, text, static_cast<int>(std::strlen(text)));
		XFreeFont(display, font);
	}

	XSetWindowBackgroundPixmap(display, static_cast<Window>(window), canvas);
	XClearWindow(display, static_cast<Window>(window));
	XFreeGC(display, gc);
	XFlush(display);
}

